#pragma once

//------------------------------------------------------
// Digital Twin Execution Mode
//------------------------------------------------------

enum TwinExecutionMode
{
    TWIN_PHYSICS = 0,
    TWIN_AI      = 1,
    TWIN_HYBRID  = 2
};


//------------------------------------------------------
// Digital Twin Configuration
//------------------------------------------------------

struct TwinConfig
{
    //--------------------------------------------------
    // Execution mode
    //--------------------------------------------------

    TwinExecutionMode mode;

    //--------------------------------------------------
    // Model enables
    //--------------------------------------------------

    bool enablePhysics;
    bool enableAI;
    bool enableResidual;

    //--------------------------------------------------
    // Validation
    //--------------------------------------------------

    bool enableValidation;

    //--------------------------------------------------
    // Physics configuration
    //--------------------------------------------------

    int gridSize;
    int physicsSteps;

    //--------------------------------------------------
    // V6 Stateful Twin
    //--------------------------------------------------

    bool enableStateEvolution;

    //--------------------------------------------------
    // Initial state
    //--------------------------------------------------

    float initialSOC;
    float initialSOH;
    float initialTemperature_C;

    //--------------------------------------------------
    // Default timestep
    //--------------------------------------------------

    float defaultDt_s;
};