#pragma once

//------------------------------------------------------
// External input to the Digital Twin
//------------------------------------------------------

struct TwinInput
{
    //--------------------------------------------------
    // BMS / external operating inputs
    //--------------------------------------------------

    float current_A;
    float soc;
    float soh;

    //--------------------------------------------------
    // Measured / initial temperature
    //--------------------------------------------------

    float temperature_C;

    //--------------------------------------------------
    // Simulation timestep
    //--------------------------------------------------

    float dt_s;
};


//------------------------------------------------------
// Stateful Digital Twin State
//------------------------------------------------------

struct TwinState
{
    //--------------------------------------------------
    // Time
    //--------------------------------------------------

    float time_s;

    //--------------------------------------------------
    // Electrical state
    //--------------------------------------------------

    float soc;
    float soh;
    float current_A;

    //--------------------------------------------------
    // Thermal state
    //--------------------------------------------------

    float temperature_C;

    float tMin_C;
    float tMax_C;
    float tMean_C;
    float tCenter_C;

    float thermalRange_C;

    //--------------------------------------------------
    // Electro-thermal state
    //--------------------------------------------------

    float resistance_ohm;
    float heatGeneration_W;

    //--------------------------------------------------
    // Previous state
    //--------------------------------------------------

    float previousSOC;
    float previousSOH;
    float previousTemperature_C;

    //--------------------------------------------------
    // State transition
    //--------------------------------------------------

    float dt_s;
};


//------------------------------------------------------
// Digital Twin Output
//------------------------------------------------------

struct TwinOutput
{
    //--------------------------------------------------
    // Thermal prediction
    //--------------------------------------------------

    float predicted_Tmax_C;
    float predicted_Tmin_C;
    float predicted_Tmean_C;

    float thermalRange_C;

    //--------------------------------------------------
    // Validation
    //--------------------------------------------------

    float predictionError_C;

    //--------------------------------------------------
    // Performance
    //--------------------------------------------------

    float inferenceTime_ms;

    //--------------------------------------------------
    // Execution mode
    //--------------------------------------------------

    int executionMode;
};